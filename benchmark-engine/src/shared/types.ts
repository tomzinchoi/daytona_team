/** Scores are in [0, 1]. Durations are milliseconds. Memory is MiB. */
export type ModelId = "qwen3-4b" | "deepseek-r1-distill-qwen-7b" | "gemma-3-4b";
export type EvidenceKind = "MEASURED" | "PREDICTED";
export type CommandSpec = { executable: "node"; args: string[] };

export interface BenchmarkCase {
  id: string;
  title: string;
  instruction: string;
  /** Files supplied to the model. Only editableFiles may be changed. */
  files: Record<string, string>;
  editableFiles: string[];
  evaluation: {
    /** Trusted evaluator files; restore after applying the generated patch. */
    files: Record<string, string>;
    buildCommand: CommandSpec;
    testCommand: CommandSpec;
    expectedTests: number;
  };
}

export interface Workload {
  id: string;
  version: string;
  name: string;
  kind: "CODING";
  description: string;
  cases: BenchmarkCase[];
  qualityPolicy: {
    testWeight: number;
    buildWeight: number;
    taskWeight: number;
    acceptableQuality: number;
  };
}

export interface ModelProfile {
  id: ModelId;
  name: string;
  role: string;
  prediction: {
    kind: "PREDICTED";
    reasoning: number;
    coding: number;
    instructionFollowing: number;
    verification: number;
    speedTokensPerSecond: number;
    memoryMb: number;
    rationale: string;
  };
}

export interface AgentSpec {
  id: string;
  modelId: ModelId;
  role: "PLANNER" | "IMPLEMENTER" | "REVIEWER";
  instruction: string;
}

export interface ArchitectureTopology {
  kind: "SINGLE" | "SEQUENTIAL";
  /** agents[] is the execution order; these edges must join consecutive agents. */
  edges: { from: string; to: string }[];
}

export interface ComputeConfig {
  id: "compact" | "standard" | "extended";
  /** Requested execution resources; the provider must honor or reject these. */
  requestedCpuCores: number;
  requestedMemoryMb: number;
  accelerator: "CPU_ONLY";
  maxOutputTokensPerAgent: number;
  timeoutMsPerCase: number;
  maxConcurrentCases: 1;
  modelHosting: "PROVIDER_MANAGED";
}

export interface Architecture {
  id: string;
  family: "A" | "B" | "C" | "D" | "E";
  name: string;
  topology: ArchitectureTopology;
  agents: AgentSpec[];
  outputAgentId: string;
  compute: ComputeConfig;
}

export interface ProviderStatus {
  id: string;
  name: string;
  status: "READY" | "UNAVAILABLE" | "NOT_CONFIGURED";
  executionEnvironment: "DAYTONA" | "LOCAL" | "OTHER";
  detail: string;
}

export interface CaseEvidence {
  caseId: string;
  status: "COMPLETED" | "TIMEOUT" | "ERROR";
  buildSucceeded: boolean;
  tests: { passed: number; failed: number; skipped: number };
}

export interface QualityAssessment {
  kind: "MEASURED";
  score: number;
  testPassRate: number;
  buildSuccessRate: number;
  taskSuccessRate: number;
  rationale: string[];
  evidence: CaseEvidence[];
}

export interface ResourceUsage {
  /** Total for the full workload, including all agents. null means unavailable. */
  costUsd: number | null;
  computeTimeMs: number | null;
  /** Required to compare computeTimeMs: identical hardware + accounting unit. */
  computeTimeBasis: string | null;
  peakMemoryMb: number | null;
  /** Describe actual inference hardware, quantization, and telemetry scope. */
  measurementContext: string;
}

export interface MeasuredMetrics {
  kind: "MEASURED";
  quality: QualityAssessment;
  /** Full-workload wall time, including every agent, evaluation, and overhead. */
  latencyMs: number;
  resource: ResourceUsage;
}

export interface PredictedMetrics {
  kind: "PREDICTED";
  quality: { kind: "PREDICTED"; score: number; rationale: string[] };
  latencyMs: number;
  resource: { kind: "PREDICTED"; relativeCompute: number; peakMemoryMb: number };
}

export type BenchmarkMetrics = MeasuredMetrics | PredictedMetrics;

interface ResultIdentity {
  id: string;
  workloadId: string;
  workloadVersion: string;
  /** SHA-256 of the complete workload contract, generated by workloadFingerprint. */
  workloadFingerprint: string;
  architecture: Architecture;
  modelIds: ModelId[];
  provider: ProviderStatus;
}

export interface MeasuredBenchmarkResult extends ResultIdentity {
  kind: "MEASURED";
  /** Derived from case evidence; never from a model's self-report. */
  succeeded: boolean;
  measuredAt: string;
  metrics: MeasuredMetrics;
}

export interface PredictedBenchmarkResult extends ResultIdentity {
  kind: "PREDICTED";
  succeeded: null;
  metrics: PredictedMetrics;
  screeningScore: number;
  assumptions: string[];
}

export type BenchmarkResult = MeasuredBenchmarkResult | PredictedBenchmarkResult;
export type ResourceMetric = "costUsd" | "computeTimeMs" | "peakMemoryMb";
export interface OptimizationWeights { quality: number; latency: number; resource: number }

export interface Recommendation {
  category: "PERFORMANCE" | "BALANCED" | "EFFICIENT";
  kind: "MEASURED";
  resultId: string;
  architectureId: string;
  quality: number;
  latencyMs: number;
  resource: { metric: ResourceMetric; value: number } | null;
  score: number | null;
  rationale: string;
  claim: "Best among evaluated configurations for this workload.";
}

export interface ArchitecturesRequest { workload: Workload }
export interface ArchitecturesResponse {
  candidateArchitectures: Architecture[];
  /** Ranked Top 3; Session 2 runs each entry's architecture. */
  screenedArchitectures: PredictedBenchmarkResult[];
  screeningKind: "PREDICTED";
}

export interface RecommendRequest {
  workload: Workload;
  results: MeasuredBenchmarkResult[];
  weights?: OptimizationWeights;
  acceptableQuality?: number;
  resourceMetric?: ResourceMetric;
}

export interface RecommendResponse {
  kind: "MEASURED";
  paretoFrontier: MeasuredBenchmarkResult[];
  performance: Recommendation | null;
  balanced: Recommendation | null;
  efficient: Recommendation | null;
  resourceMetric: ResourceMetric | null;
  weights: OptimizationWeights;
  acceptableQuality: number;
  evaluatedCount: number;
  warnings: string[];
  claim: "Best among evaluated configurations for this workload.";
}
